def _init_py(spec: ProjectSpec) -> str:
    return f'"""{spec.project_name} package."""\n\n__version__ = "0.1.0"\n'


def _main_py(spec: ProjectSpec) -> str:
    return (
        f'"""Entry point for {spec.project_name}."""\n'
        "\n\n"
        "def main() -> None:\n"
        f'    """Run {spec.project_name}."""\n'
        f'    print("Hello from {spec.project_name}")\n'
        "\n\n"
        'if __name__ == "__main__":\n'
        "    main()\n"
    )


def _cli_py(spec: ProjectSpec) -> str:
    name = spec.project_name
    if spec.framework == "typer":
        return (
            f'"""Command-line interface for {name}."""\n\n'
            "import typer\n\n"
            "app = typer.Typer()\n\n\n"
            "@app.command()\n"
            "def main() -> None:\n"
            f'    """Run {name}."""\n'
            f'    typer.echo("Hello from {name}")\n'
            "\n\n"
            'if __name__ == "__main__":\n'
            "    app()\n"
        )
    if spec.framework == "click":
        return (
            f'"""Command-line interface for {name}."""\n\n'
            "import click\n\n\n"
            "@click.command()\n"
            "def main() -> None:\n"
            f'    """Run {name}."""\n'
            f'    click.echo("Hello from {name}")\n'
            "\n\n"
            'if __name__ == "__main__":\n'
            "    main()\n"
        )
    return (
        f'"""Command-line interface for {name}."""\n\n'
        "import argparse\n\n\n"
        "def main() -> None:\n"
        f'    """Run {name}."""\n'
        f'    parser = argparse.ArgumentParser(description="{name}")\n'
        "    parser.parse_args()\n"
        f'    print("Hello from {name}")\n'
        "\n\n"
        'if __name__ == "__main__":\n'
        "    main()\n"
    )


def _web_main_py(spec: ProjectSpec) -> str:
    name = spec.project_name
    if spec.framework == "fastapi":
        return (
            f'"""FastAPI application entry point for {name}."""\n\n'
            "from fastapi import FastAPI\n\n"
            f'app = FastAPI(title="{name}")\n\n\n'
            '@app.get("/")\n'
            "def root() -> dict[str, str]:\n"
            '    """Return a simple greeting."""\n'
            f'    return {{"message": "Hello from {name}"}}\n'
        )
    if spec.framework == "flask":
        return (
            f'"""Flask application entry point for {name}."""\n\n'
            "from flask import Flask\n\n"
            "app = Flask(__name__)\n\n\n"
            '@app.get("/")\n'
            "def root() -> str:\n"
            '    """Return a simple greeting."""\n'
            f'    return "Hello from {name}"\n'
        )
    return _main_py(spec)


def _readme(spec: ProjectSpec) -> str:
    return (
        f"# {spec.project_name}\n\n"
        f"Generated by **mkpj** with the **{spec.profile}** profile.\n\n"
        "## Test\n\n"
        "```bash\n"
        f"{venv_python_path()} -m pytest\n"
        "```\n"
    )


def _test_main(pkg_name: str) -> str:
    return (
        f"from {pkg_name}.main import main\n\n\n"
        "def test_main_runs(capsys):\n"
        "    main()\n"
        "    captured = capsys.readouterr()\n"
        '    assert "Hello" in captured.out\n'
    )


def _test_cli(pkg_name: str) -> str:
    return (
        f"from {pkg_name}.cli import main\n\n\n"
        "def test_cli_entrypoint_exists():\n"
        "    assert callable(main)\n"
    )


def _test_app(pkg_name: str) -> str:
    return (
        f"from {pkg_name}.main import app\n\n\n"
        "def test_app_exists():\n"
        "    assert app is not None\n"
    )


# ---------------------------------------------------------------------------
# Writer
# ---------------------------------------------------------------------------
def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def write_project_files(spec: ProjectSpec) -> None:
    root = spec.root
    _write(root / "pyproject.toml", render_pyproject(spec))
    _write(root / "README.md", _readme(spec))
    _write(root / ".gitignore", GITIGNORE)

    if spec.profile != "minimal":
        _write(root / ".env.example", ENV_EXAMPLE)

    _write(spec.src_dir / "__init__.py", _init_py(spec))

    if spec.files_mode == "cli":
        _write(spec.src_dir / "cli.py", _cli_py(spec))
    elif spec.files_mode == "web":
        _write(spec.src_dir / "main.py", _web_main_py(spec))
    else:
        _write(spec.src_dir / "main.py", _main_py(spec))

    if spec.profile != "minimal":
        _write(root / "tests" / "__init__.py", "")
        if spec.files_mode == "cli":
            _write(root / "tests" / "test_cli.py", _test_cli(spec.pkg_name))
        elif spec.files_mode == "web":
            if spec.framework in ("fastapi", "flask"):
                _write(root / "tests" / "test_app.py", _test_app(spec.pkg_name))
            else:
                _write(root / "tests" / "test_main.py", _test_main(spec.pkg_name))
        else:
            _write(root / "tests" / "test_main.py", _test_main(spec.pkg_name))

    if spec.profile in ("data", "ml", "dl", "research"):
        _write(root / "notebooks" / "README.md", NOTEBOOKS_README)

    if spec.profile == "library":
        _write(spec.src_dir / "py.typed", "")

    if spec.profile == "cli":
        with open(root / "pyproject.toml", "a", encoding="utf-8") as handle:
            handle.write(
                "\n[project.scripts]\n"
                f'{spec.project_name} = "{spec.pkg_name}.cli:main"\n'
            )

    if spec.example_workflow:
        write_example(spec)


def write_example(spec: ProjectSpec) -> None:
    if spec.profile not in ("ml", "dl"):
        return
    examples = spec.root / "examples"
    examples.mkdir(parents=True, exist_ok=True)

    if spec.profile == "ml" and spec.framework == "scikit-learn":
        _write(examples / "baseline.py", SKLEARN_EXAMPLE)
    elif spec.profile == "dl" and spec.framework == "pytorch":
        _write(examples / "baseline.py", PYTORCH_EXAMPLE)
    else:
        _write(examples / "README.md", _example_readme(spec.framework))


def write_vscode(spec: ProjectSpec) -> None:
    vscode = spec.root / ".vscode"
    vscode.mkdir(parents=True, exist_ok=True)
    _write(vscode / "settings.json", render_vscode_settings(spec))
    _write(vscode / "extensions.json", render_vscode_extensions(spec.extensions))
