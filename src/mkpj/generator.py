"""Writes the generated project tree.

Every template below is pinned byte for byte by the tests, so a
project generated by either implementation is indistinguishable.
"""

from __future__ import annotations

import os
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path

from .profiles import Tooling

__all__ = [
    "ProjectSpec",
    "render_pyproject",
    "render_vscode_settings",
    "write_project_files",
    "venv_python_path",
    "IS_WINDOWS",
]


# Resolved once, at import. Tests override this attribute to render the other
# platform's layout; patching os.name instead would also repoint pathlib, which
# then refuses to build a WindowsPath on POSIX (and vice versa).
IS_WINDOWS = os.name == "nt"


def venv_python_path(prefix: str = ".venv") -> str:
    if IS_WINDOWS:
        return f"{prefix}/Scripts/python.exe"
    return f"{prefix}/bin/python"


@dataclass
class ProjectSpec:
    project_name: str
    pkg_name: str
    profile: str
    files_mode: str
    framework: str
    tooling: Tooling
    root: Path
    dev_packages: list[str] = field(default_factory=list)
    runtime_packages: list[str] = field(default_factory=list)
    extensions: list[str] = field(default_factory=list)
    py_major: int = 3
    py_minor: int = 9
    requires_python: str = ">=3.9"
    example_workflow: bool = False

    @property
    def src_dir(self) -> Path:
        return self.root / "src" / self.pkg_name


# ---------------------------------------------------------------------------
# Small renderers
# ---------------------------------------------------------------------------
def _toml_list(items: Sequence[str]) -> str:
    # An empty list still yields the blank line between the brackets.
    if not items:
        return ""
    return "\n".join(f'    "{item}",' for item in items)


def _json_list(items: Sequence[str]) -> str:
    if not items:
        return ""
    return ",\n".join(f'        "{item}"' for item in items)


def render_pyproject(spec: ProjectSpec) -> str:
    t = spec.tooling
    parts = [
        "[build-system]\n"
        'requires = ["setuptools>=68"]\n'
        'build-backend = "setuptools.build_meta"\n'
        "\n"
        "[project]\n"
        f'name = "{spec.project_name}"\n'
        'version = "0.1.0"\n'
        'description = ""\n'
        f'requires-python = "{spec.requires_python}"\n'
        'readme = "README.md"\n'
        "dependencies = [\n"
        f"{_toml_list(spec.runtime_packages)}\n"
        "]\n"
        "\n"
        "[dependency-groups]\n"
        "dev = [\n"
        f"{_toml_list(spec.dev_packages)}\n"
        "]\n"
        "\n"
    ]

    if t.quality == "ruff":
        parts.append(
            "\n[tool.ruff]\n"
            "line-length = 100\n"
            f'target-version = "py{spec.py_major}{spec.py_minor}"\n'
            "\n"
            "[tool.ruff.lint]\n"
            'select = ["E", "F", "I", "B", "UP"]\n'
        )

    if t.testing in ("pytest", "pytest_cov"):
        parts.append("\n[tool.pytest.ini_options]\ntestpaths = [\"tests\"]\n")

    if t.type_checker == "mypy":
        parts.append(
            "\n[tool.mypy]\n"
            f'python_version = "{spec.py_major}.{spec.py_minor}"\n'
            "ignore_missing_imports = true\n"
        )

    if t.quality in ("black_pylint", "black_flake8"):
        parts.append('\n[tool.black]\nline-length = 100\ntarget-version = ["py39"]\n')

    return "".join(parts)


def render_vscode_settings(spec: ProjectSpec) -> str:
    t = spec.tooling
    formatter = ""
    if t.quality == "ruff":
        formatter = "charliermarsh.ruff"
    elif t.quality in ("black_pylint", "black_flake8"):
        formatter = "ms-python.black-formatter"

    pytest_enabled = "true" if t.testing in ("pytest", "pytest_cov") else "false"
    format_on_save = "false" if spec.profile == "learner" else "true"

    code_actions = '        "source.organizeImports": "explicit"'
    if formatter:
        code_actions += ',\n        "source.fixAll": "explicit"'

    python_block = ""
    if formatter:
        python_block = (
            ',\n    "[python]": {\n'
            f'        "editor.defaultFormatter": "{formatter}"\n'
            "    }"
        )

    return (
        "{\n"
        f'    "python.defaultInterpreterPath": '
        f'"${{workspaceFolder}}/{venv_python_path()}",\n'
        f'    "python.testing.pytestEnabled": {pytest_enabled},\n'
        '    "python.testing.pytestArgs": ["tests"],\n'
        f'    "editor.formatOnSave": {format_on_save},\n'
        '    "editor.codeActionsOnSave": {\n'
        f"{code_actions}\n"
        "    }"
        f"{python_block}\n"
        "}\n"
    )


def render_vscode_extensions(extensions: Sequence[str]) -> str:
    return '{\n    "recommendations": [\n' f"{_json_list(extensions)}\n" "    ]\n}\n"


